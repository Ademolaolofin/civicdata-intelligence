def show_selected_metrics(manifest):
    """
    Display one record per implemented/planned metric.
    """

    unique = (
        manifest[
            [
                "metric_id",
                "metric_name",
                "data_provider",
                "data_collection",
                "implementation_batch",
                "implementation_status",
            ]
        ]
        .drop_duplicates(
            subset=[
                "metric_id"
            ]
        )
        .sort_values(
            [
                "implementation_batch",
                "metric_name",
            ]
        )
    )

    print(
        "\n=== CIVICDATA LOF V0.1 METRICS ==="
    )

    print(
        unique.to_string(
            index=False
        )
    )


def show_cross_outcome_metrics(
    manifest,
):
    """
    Report selected metrics appearing under more than one
    official LOF outcome.
    """

    counts = (
        manifest.groupby(
            [
                "metric_id",
                "metric_name",
            ]
        )[
            "outcome_id"
        ]
        .nunique()
        .reset_index(
            name="outcome_count"
        )
    )

    cross_outcome = counts[
        counts[
            "outcome_count"
        ] > 1
    ]

    print(
        "\n=== CROSS-OUTCOME METRICS ==="
    )

    if cross_outcome.empty:
        print(
            "None in current v0.1 selection."
        )

        return

    for _, metric in (
        cross_outcome.iterrows()
    ):
        print(
            f"\n{metric['metric_name']}"
        )

        relationships = (
            manifest[
                manifest[
                    "metric_id"
                ].eq(
                    metric[
                        "metric_id"
                    ]
                )
            ][
                [
                    "outcome_id",
                    "outcome_name",
                ]
            ]
            .drop_duplicates()
            .sort_values(
                "outcome_id"
            )
        )

        for _, relationship in (
            relationships.iterrows()
        ):
            print(
                f"  "
                f"{int(relationship['outcome_id']):02d} "
                f"{relationship['outcome_name']}"
            )


