# MAIN
# =========================================================

def main():
    print(
        "\n========================================"
    )

    print(
        "CIVICDATA LOF V0.1 IMPLEMENTATION "
        "MANIFEST"
    )

    print(
        "========================================"
    )

    catalogue = load_catalogue()

    selections = resolve_selections(
        catalogue
    )

    manifest = build_manifest(
        catalogue,
        selections,
    )

    validate_manifest(
        manifest,
        selections,
    )

    save_manifest(
        manifest
    )

    show_selected_metrics(
        manifest
    )

    show_cross_outcome_metrics(
        manifest
    )

    print(
        "\n=== COMPLETE ==="
    )

    print(
        "The CivicData LOF v0.1 manifest "
        "has been built from existing official "
        "catalogue metrics."
    )

    print(
        "No LOF metrics or statistical-neighbour "
        "relationships were created or inferred "
        "by CivicData."
    )


if __name__ == "__main__":
    main()